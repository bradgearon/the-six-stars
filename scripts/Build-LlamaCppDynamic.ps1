param(
  [switch]$WithCuda = $true,
  [switch]$WithVulkan,
  [switch]$Clean,
  [string]$CudaArchitectures = "auto",
  [int]$BuildParallel = 2,
  [bool]$UseDynamicBackends = $false,
  [string]$SourceDir = "build/llama.cpp",
  [string]$OutDir = "engines/llm/llama-cpp-dynamic-win-x64",
  [string]$RepoUrl = "https://github.com/ggml-org/llama.cpp.git"
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

function To-OnOff([bool]$value) {
  if ($value) { return "ON" }
  return "OFF"
}

function Resolve-CudaArch([string]$requested) {
  if (!$WithCuda) { return $null }
  if (![string]::IsNullOrWhiteSpace($requested) -and $requested -ne "auto") { return $requested }

  try {
    $caps = & nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>$null
    if ($LASTEXITCODE -eq 0 -and $caps) {
      $first = ($caps | Select-Object -First 1).Trim()
      if ($first -match '^(\d+)\.(\d+)$') {
        return "$($Matches[1])$($Matches[2])"
      }
    }
  } catch { }

  # Safe fallback for RTX 30xx/Ampere. Override with -CudaArchitectures if needed.
  return "86"
}

New-Item -ItemType Directory -Force -Path "build" | Out-Null
if (!(Test-Path $SourceDir)) {
  Write-Host "Cloning llama.cpp into $SourceDir"
  git clone --depth 1 $RepoUrl $SourceDir
} else {
  Write-Host "Updating llama.cpp in $SourceDir"
  git -C $SourceDir pull --ff-only
}

$buildDir = Join-Path $SourceDir "build-dynamic"
if ($Clean -and (Test-Path $buildDir)) {
  Write-Host "Cleaning previous llama.cpp build: $buildDir"
  Remove-Item $buildDir -Recurse -Force
}

# Stable default:
# - Do not build Vulkan for NVIDIA profiles. Current Vulkan shader generation can crash glslc.
# - Do not build every CPU backend variant unless dynamic backend loading is explicitly requested.
# - Limit CUDA architecture to the local GPU so CUDA 13.x does not try Blackwell 120a/121a code paths on older cards.
# - Limit parallelism; MSVC/nvcc can crash when many heavy CPU/CUDA/Vulkan targets compile at once.
$backendDl = $UseDynamicBackends
$cpuAllVariants = $UseDynamicBackends
$cudaArch = Resolve-CudaArch $CudaArchitectures

$cmakeArgs = @(
  "-S", $SourceDir,
  "-B", $buildDir,
  "-DGGML_BACKEND_DL=$(To-OnOff $backendDl)",
  "-DGGML_CPU_ALL_VARIANTS=$(To-OnOff $cpuAllVariants)",
  "-DGGML_NATIVE=OFF",
  "-DBUILD_SHARED_LIBS=ON",
  "-DGGML_CCACHE=OFF",
  "-DCMAKE_BUILD_TYPE=Release",
  "-DLLAMA_BUILD_TESTS=OFF"
)

if ($WithCuda) {
  $cmakeArgs += "-DGGML_CUDA=ON"
  if ($cudaArch) { $cmakeArgs += "-DCMAKE_CUDA_ARCHITECTURES=$cudaArch" }
} else {
  $cmakeArgs += "-DGGML_CUDA=OFF"
}

if ($WithVulkan) { $cmakeArgs += "-DGGML_VULKAN=ON" } else { $cmakeArgs += "-DGGML_VULKAN=OFF" }

Write-Host "Configuring llama.cpp stable build..."
Write-Host "CUDA enabled:   $WithCuda"
Write-Host "CUDA arch:      $cudaArch"
Write-Host "Vulkan enabled: $WithVulkan"
Write-Host "Dynamic DL:     $UseDynamicBackends"
Write-Host "Parallel jobs:  $BuildParallel"
Write-Host "cmake $($cmakeArgs -join ' ')"
cmake @cmakeArgs

Write-Host "Building llama.cpp llama-server target..."
cmake --build $buildDir --config Release --target llama-server --parallel $BuildParallel
if ($LASTEXITCODE -ne 0) { throw "llama.cpp build failed with exit code $LASTEXITCODE" }

New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$exe = Get-ChildItem $buildDir -Recurse -Filter "llama-server.exe" | Select-Object -First 1
if (!$exe) { throw "Could not find llama-server.exe under $buildDir" }
Copy-Item $exe.FullName $OutDir -Force

# Copy backend/common runtime DLLs next to llama-server.exe.
Get-ChildItem $buildDir -Recurse -Include "*.dll" | ForEach-Object {
  Copy-Item $_.FullName $OutDir -Force
}

@"
This folder is generated by scripts/Build-LlamaCppDynamic.ps1.
The folder name still says dynamic for compatibility with the existing launcher,
but the default build is now a stable CUDA/CPU llama-server build.

Default stability flags:
- GGML_BACKEND_DL=OFF
- GGML_CPU_ALL_VARIANTS=OFF
- GGML_NATIVE=OFF
- GGML_VULKAN=OFF unless -WithVulkan is explicitly supplied
- CMAKE_CUDA_ARCHITECTURES is detected from nvidia-smi, usually 86 for RTX 30xx
- build target is llama-server only, with low parallelism

Why:
- Dynamic backend + all CPU variants caused MSVC CL.exe crashes on some systems.
- Vulkan shader generation caused glslc crashes on this machine.
- CUDA 13.x tried 120a/121a architectures and crashed ptxas/cicc on this machine.
"@ | Set-Content (Join-Path $OutDir "README.txt") -Encoding UTF8

Write-Host "llama.cpp runtime copied to $OutDir" -ForegroundColor Green
